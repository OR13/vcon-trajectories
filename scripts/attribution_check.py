#!/usr/bin/env python3
"""Check derived `file_attribution` against SWE-chat's own per-session attribution labels.

SWE-chat labels each session with `files_touched` (files in the commits it produced) and
`agent_lines` (committed lines attributed to the agent). For Codex sessions we derive
`file_attribution` from `patch_apply_end` diffs and compare:

  file recall      share of SWE-chat `files_touched` that we attribute
  file precision   share of our attributed files that SWE-chat lists
  line ratio       our attributed lines / SWE-chat `agent_lines` (on sessions where both exist)

These are different measurements (we replay the session's edits; SWE-chat attributes committed lines),
so agreement is a sanity check, not ground truth.

    python scripts/attribution_check.py [N]       # N Codex sessions (default 80); writes docs/attribution-check.md
"""
import json
import os
import statistics
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(HERE, "src"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import corpora as C  # noqa: E402
from vcon_trajectories.ai_agent import utrajectory_to_vcon  # noqa: E402
from vcon_trajectories.native import codex  # noqa: E402
from vcon_trajectories.validate import CddlValidator, semantic_issues  # noqa: E402


def main(n):
    labels = {r["session_id"]: r for r in C._swechat_sessions_full()}
    v = CddlValidator()
    rows = []
    for sid, recs in C.swechat_native("Codex", n, max_turns=400, min_turns=1):
        ut = codex.parse(recs, source="SALT-NLP/SWE-chat", id=sid)
        vc = utrajectory_to_vcon(ut)
        ok, msg = v.validate(vc)
        fa = vc.get("file_attribution", {}).get("files", [])
        ours = {f["path"]: sum(r["end_line"] - r["start_line"] + 1 for c in f["conversations"] for r in c["ranges"]) for f in fa}
        lab = labels.get(sid) or {}
        touched = set(json.loads(lab["files_touched"])) if lab.get("files_touched") else set()
        rows.append(dict(sid=sid, valid=ok and not semantic_issues(vc), edits=len(ut.file_edits), has_fa=bool(fa),
                         ours=ours, touched=touched, agent_lines=lab.get("agent_lines"), n_ours=sum(ours.values())))
    withfa = [r for r in rows if r["has_fa"]]
    rec, prec, ratio = [], [], []
    for r in withfa:
        match = {p for p in r["ours"] if any(t == p or t.endswith("/" + p) or p.endswith("/" + t) for t in r["touched"])}
        if r["touched"]:
            rec.append(len({t for t in r["touched"] if any(t == p or t.endswith("/" + p) or p.endswith("/" + t) for p in r["ours"])}) / len(r["touched"]))
        prec.append(len(match) / len(r["ours"]))
        if r["agent_lines"]:
            ratio.append(r["n_ours"] / r["agent_lines"])
    med = lambda x: f"{statistics.median(x):.2f}" if x else "n/a"
    out = ["# Attribution check (Codex · SWE-chat)", "",
           "Generated by `scripts/attribution_check.py`. Derived `file_attribution` vs SWE-chat's labels "
           "(different measurements; a sanity check, not ground truth).", "",
           f"- Codex sessions with transcripts: {len(rows)}; with at least one replayable edit: {len(withfa)}",
           f"- vCons valid (CDDL + semantic): {sum(r['valid'] for r in rows)}/{len(rows)}",
           f"- median file recall (SWE-chat `files_touched` we attribute): {med(rec)} over {len(rec)} sessions",
           f"- median file precision (our files SWE-chat also lists): {med(prec)} over {len(prec)} sessions",
           f"- median line ratio (ours / SWE-chat `agent_lines`): {med(ratio)} over {len(ratio)} sessions",
           ]
    open(os.path.join(HERE, "docs", "attribution-check.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 80)
